"""Build the stripped target list for a batch's input-issue second opinion (see `plan.md`).

Targets: every ledger row classified input-issue, every row whose Error tag includes
dosage_medication_mismatch, every row whose rating has a non-empty expected_flag_for, and every
row ID named in the adjudication file's "Classification disagreements" section. Strips
Classification, Input named, Conflict-flag basis, Expected behavior and Provenance, so the
second-opinion agent classifies independently.
Run from the round folder:  python3 -I <skill>/scripts/make_second_opinion_input.py <BATCH>
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from mechanical_check import ledger_rows, col  # noqa: E402

if len(sys.argv) != 2:
    print("usage: make_second_opinion_input.py <BATCH>", file=sys.stderr)
    sys.exit(1)
b = sys.argv[1]
rows = ledger_rows(b)
if rows is None:
    print(f"make_second_opinion_input.py: ledger/{b}.md not found", file=sys.stderr)
    sys.exit(1)
qa_dir = os.path.join("ledger", "qa")
os.makedirs(qa_dir, exist_ok=True)
adj = os.path.join(qa_dir, f"{b}-adjudication.md")
named = set()
if os.path.exists(adj):
    t = open(adj).read()
    m = re.search(r"#+[^\n]*Classification disagreements[^\n]*\n(.*?)(?=\n#+ |\Z)", t, re.S | re.I)
    if m:
        named = set(re.findall(rf"\b{b}-\d{{3}}\b", m.group(1)))


def required(r):
    return col(r, "classification") == "input-issue" or "dosage_medication_mismatch" in col(r, "error tag") or col(r, "row id") in named


# The round's rule requires the rows above. All other issue rows are added too, so the second
# opinion can catch a draft-controlled call that is really an input (goal: file nothing that is
# an input issue).
keep = [r for r in rows if required(r) or (col(r, "provenance") != "thumbs-only" and "audited, no issue found" not in col(r, "atomic issue"))]
cols = ["required", "row id", "trace id", "reviewer", "rating ref", "error tag", "verbatim reviewer quote", "offending draft sentence", "atomic issue"]
L = [f"# Second-opinion targets, batch {b} (stripped)", "",
     "Generated by `make_second_opinion_input.py`. Classification and the extractor's reasoning are removed on purpose.", "",
     "| " + " | ".join(c.title() for c in cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
for r in keep:
    L.append("| " + " | ".join(("yes" if required(r) else "no") if c == "required" else col(r, c) for c in cols) + " |")
out = os.path.join(qa_dir, f"{b}-second-opinion-targets.md")
open(out, "w").write("\n".join(L) + "\n")
print(f"{b}: {len(keep)} target rows, {sum(required(r) for r in keep)} required ({sum(col(r,'classification')=='input-issue' for r in keep)} input-issue, "
      f"{sum('dosage_medication_mismatch' in col(r,'error tag') for r in keep)} dosage_medication_mismatch, {len(named)} named by adjudicator) -> {out}")
