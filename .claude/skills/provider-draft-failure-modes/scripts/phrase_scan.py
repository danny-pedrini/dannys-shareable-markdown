"""Step 2b cross-type phrase scan (see `plan.md`).

Reads every draft from export/<code>.md (the "Provider draft" block; records reading
`(no draft generated)` are skipped), splits them into sentences, and reports sentences and
6-word runs that repeat across drafts, with counts by batch. Weights, ages, dates and postpartum
durations are masked before counting, so a templated line such as "goal weight of 185 pounds"
and "goal weight of 147 pounds" count as one phrase: a masked match counts as identical text.
Section 1 lists every sentence in 2 or more drafts with full trace IDs, the input for
`cluster_defs.SPREAD_TRACES`.
Run from the round folder:  python3 -I <skill>/scripts/phrase_scan.py
Writes ledger/qa/phrase-scan.md.
"""
import collections
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.getcwd()
sys.path.insert(0, HERE)
import round_config as RC  # noqa: E402
import check_export as CE  # noqa: E402

SENTENCE_MIN = 2

MONTHS = r"(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]*\.?"


def mask(s):
    s = re.sub(r"\b\d+(?:\.\d+)?\s*(?:lbs?|pounds)\b", "[redacted] pounds", s)
    s = re.sub(r"\b\d{1,3}(?:-year-old| years old| years of age)\b", "[redacted] years", s)
    s = re.sub(r"\b" + MONTHS + r"\s+\d{1,2}(?:st|nd|rd|th)?\b", "[redacted date]", s)
    s = re.sub(r"\b\d{1,2}/\d{1,2}(?:/\d{2,4})?\b", "[redacted date]", s)
    s = re.sub(r"\b\w+ weeks postpartum\b", "[redacted] postpartum", s)
    return s


def drafts(codes):
    out = []
    for b in codes:
        path = os.path.join(ROOT, "export", b + ".md")
        if not os.path.exists(path):
            continue
        txt = open(path).read()
        for c in re.split(r"\n(?=## \d+\. )", txt)[1:]:
            tm = re.search(r"\*Trace (tr-[0-9a-fA-F]{32})", c)
            d = CE.draft_text_of(c)
            if tm and d:
                out.append((b, tm.group(1), d))
    return out


def sentences(d):
    d = d.replace("{{provider_intro}}", "\n{{provider_intro}}\n")
    d = re.sub(r"(?<=[a-z0-9\)\]])(?=[A-Z])", "\n", d)        # Doc collapsed paragraph breaks
    parts = re.split(r"(?<=[.!?])\s+|\n+", d)
    return [p.strip() for p in parts if len(p.strip().split()) >= 4]


def norm(s):
    return re.sub(r"\s+", " ", mask(s).lower()).strip(" .")


def main():
    cfg = RC.load(os.path.join(ROOT, "round.json"))
    codes = RC.batch_codes(cfg)
    D = drafts(codes)
    sent = collections.defaultdict(set)
    gram = collections.defaultdict(set)
    for b, t, d in D:
        for s in sentences(d):
            n = norm(s)
            sent[n].add((b, t))
            w = re.findall(r"[a-z0-9'\[\]\.]+", n)
            for i in range(len(w) - 5):
                gram[" ".join(w[i:i + 6])].add((b, t))
    L = ["# Cross-type phrase scan (Step 2b)", "",
         "> **Source:** the drafts in `export/<code>.md`. Generated by `phrase_scan.py`. Weights, "
         "ages, dates and postpartum durations are masked before counting.", "",
         f"## 1. Sentences repeated in {SENTENCE_MIN} or more drafts", "",
         "Trace IDs are full, so a spread entry in `cluster_defs.SPREAD_TRACES` can copy them as written.", "",
         "| Drafts | " + " | ".join(codes) + " | Sentence (masked) | Trace IDs |",
         "| --- | " + " | ".join("---" for _ in codes) + " | --- | --- |"]
    reps = sorted(((len(v), k, v) for k, v in sent.items() if len(v) >= SENTENCE_MIN), reverse=True)
    for n, k, v in reps:
        c = collections.Counter(b for b, _ in v)
        L.append(f"| {n} | " + " | ".join(str(c.get(b, 0)) for b in codes) + f" | {k.replace('|', '/')} | {' '.join(sorted(t for _, t in v))} |")
    L += ["", "## 2. Six-word runs in 10 or more drafts (top 80 by draft count)", "",
          "Overlapping runs from one repeated sentence appear together. Section 1 is the cleaner "
          "view; this section catches repeats inside sentences that otherwise differ.", "",
          "| Drafts | " + " | ".join(codes) + " | Six-word run |",
          "| --- | " + " | ".join("---" for _ in codes) + " | --- |"]
    top = sorted(((len(v), k, v) for k, v in gram.items() if len(v) >= 10), reverse=True)[:80]
    for n, k, v in top:
        c = collections.Counter(b for b, _ in v)
        L.append(f"| {n} | " + " | ".join(str(c.get(b, 0)) for b in codes) + f" | {k} |")
    L += ["", f"Counts: {len(D)} drafts, {sum(len(sentences(d)) for _, _, d in D)} sentences, "
          f"{len(reps)} sentences repeated in {SENTENCE_MIN}+ drafts, {len([1 for v in gram.values() if len(v) >= 10])} six-word runs in 10+ drafts."]
    os.makedirs(os.path.join(ROOT, "ledger", "qa"), exist_ok=True)
    open(os.path.join(ROOT, "ledger", "qa", "phrase-scan.md"), "w").write("\n".join(L) + "\n")
    print(f"wrote ledger/qa/phrase-scan.md: {len(D)} drafts; {len(reps)} repeated sentences ({SENTENCE_MIN}+ drafts); "
          f"top sentence in {reps[0][0] if reps else 0} drafts; "
          f"{len([1 for v in gram.values() if len(v) >= 10])} six-word runs in 10+ drafts")


if __name__ == "__main__":
    main()
